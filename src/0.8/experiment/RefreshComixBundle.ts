export {};

/**
 * Fetch the live comix.to secure-*.js bundle and regenerate
 * experiment/ComixBundle.ts (the source-of-truth the crypto pipeline reads).
 *
 * Run:
 * deno task crypto:refresh
 */

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT_FILE = resolve(import.meta.dirname!, "ComixBundle.ts");
const HOMEPAGE = Deno.env.get("COMIX_REFRESH_HOMEPAGE") ??
  "https://comix.to/title/xlyyj-eleceed";
const UA = Deno.env.get("USER_AGENT") ??
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/148.0.0.0 Safari/537.36";

function cookieHeader(): string {
  return [
    Deno.env.get("SESSION") ? `session=${Deno.env.get("SESSION")}` : "",
    Deno.env.get("CF_CLEARANCE")
      ? `cf_clearance=${Deno.env.get("CF_CLEARANCE")}`
      : "",
  ].filter(Boolean).join("; ");
}

async function fetchText(url: string, accept: string): Promise<string> {
  const res = await fetch(url, {
    headers: {
      "User-Agent": UA,
      "Accept": accept,
      "Cookie": cookieHeader(),
      "Referer": "https://comix.to/",
    },
  });
  if (!res.ok) {
    throw new Error(
      `fetch ${url} -> HTTP ${res.status}. ${
        res.status === 403 ? "CF cookie may be expired or IP-mismatched." : ""
      }`,
    );
  }
  return await res.text();
}

function transformExports(
  text: string,
): { transformed: string; exportNames: string[] } {
  const m = text.match(/export\s*\{([^}]+)\}\s*;?/);
  if (!m) throw new Error("could not locate `export {...}` in secure.js");
  const pairs = m[1]!.split(",").map((p) => {
    const parts = p.trim().split(/\s+as\s+/);
    // `export {x as y}` aliases; a bare `export {r}` exports under its own name.
    if (parts.length === 1) {
      const name = parts[0]!.trim();
      return { local: name, exported: name };
    }
    if (parts.length !== 2) throw new Error(`unexpected export pair: ${p}`);
    return { local: parts[0]!.trim(), exported: parts[1]!.trim() };
  });
  const obj = pairs.map((p) => `${p.exported}:${p.local}`).join(",");
  const replacement = `;return {${obj}};`;
  return {
    transformed: text.replace(m[0], replacement),
    exportNames: pairs.map((p) => p.exported),
  };
}

async function main(): Promise<void> {
  if (!Deno.env.get("CF_CLEARANCE")) {
    console.warn(
      "[refresh] CF_CLEARANCE not set; expect HTTP 403 from comix.to",
    );
  }

  console.log(`[refresh] fetching homepage ${HOMEPAGE}`);
  const html = await fetchText(HOMEPAGE, "text/html,*/*;q=0.9");

  const cfgM = html.match(/<meta\s+name="cfg"\s+content="([^"]+)"/);
  const mainM = html.match(/src="([^"]*main-[a-zA-Z0-9_-]+\.js)"/);
  if (!cfgM) throw new Error('could not parse <meta name="cfg">');
  if (!mainM) throw new Error("could not parse main bundle URL");
  const cfg = cfgM[1]!;
  const mainUrl = new URL(mainM[1]!, HOMEPAGE).href;

  console.log(`[refresh] cfg length ${cfg.length}; main ${mainUrl}`);
  const mainText = await fetchText(mainUrl, "application/javascript,*/*;q=0.9");

  const secureM = mainText.match(
    /from\s*["']([^"']*secure-[a-zA-Z0-9_-]+\.js)["']/,
  );
  if (!secureM) {
    throw new Error("could not find secure bundle import in main.js");
  }
  const secureUrl = new URL(secureM[1]!, mainUrl).href;

  console.log(`[refresh] secure ${secureUrl}`);
  const secureText = await fetchText(
    secureUrl,
    "application/javascript,*/*;q=0.9",
  );

  const bundleId = createHash("sha256").update(secureText).digest("hex").slice(
    0,
    12,
  );
  console.log(`[refresh] bundleId ${bundleId} (${secureText.length} bytes)`);

  const { transformed, exportNames } = transformExports(secureText);
  console.log(`[refresh] exports: ${exportNames.join(",")}`);

  const out =
    `// Generated by experiment/RefreshComixBundle.ts. DO NOT EDIT BY HAND.
// To refresh: \`deno task crypto:refresh\` (requires CF_CLEARANCE env var).

export const BUNDLE_INFO = {
    bundleId: ${JSON.stringify(bundleId)},
    fetchedAt: ${JSON.stringify(new Date().toISOString())},
    homepage: ${JSON.stringify(HOMEPAGE)},
    mainUrl: ${JSON.stringify(mainUrl)},
    secureUrl: ${JSON.stringify(secureUrl)},
    cfg: ${JSON.stringify(cfg)},
    exportNames: ${JSON.stringify(exportNames)},
} as const;

export const BUNDLE_CODE = ${JSON.stringify(transformed)};
`;
  writeFileSync(OUT_FILE, out);
  console.log(`[refresh] wrote ${OUT_FILE} (${out.length} bytes)`);
}

main().catch((e) => {
  console.error(`[refresh] FAILED: ${e?.message ?? e}`);
  Deno.exit(1);
});
